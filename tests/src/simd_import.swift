// Typecheck test: the C simd module imports into Swift with the function
// names the Swift simd overlay calls (it is compiled with `swiftc
// -typecheck`; no overlay or runtime is needed).
import simd

func check() {
    let v = SIMD3<Float>(1, 2, 3)
    let w = SIMD3<Float>(0, 1, 0)
    let _: Float = simd_dot(v, w)
    let _: Float = simd_length(v)
    let _: SIMD3<Float> = simd_cross(v, w)
    let _: SIMD3<Float> = simd_normalize(v)
    let _: SIMD3<Float> = simd_abs(v)
    let _: SIMD3<Float> = simd_min(v, w)
    let _: SIMD3<Float> = simd_max(v, w)
    let _: Float = simd_reduce_add(v)
    let _: SIMD3<Float> = simd_sign(v)
    let _: SIMD3<Float> = simd_recip(v)
    let _: SIMD3<Float> = simd_rsqrt(v)
    let _: SIMD3<Float> = simd_fract(v)
    let _: SIMD3<Float> = simd_step(v, w)
    let _: SIMD3<Float> = simd_smoothstep(v, w, v)
    let _: SIMD3<Float> = simd_project(v, w)
    let _: SIMD3<Float> = simd_reflect(v, w)
    let _: SIMD3<Float> = simd_refract(v, w, 1.5)
    let i = SIMD2<Int32>(1, -2)
    let _: SIMD2<Int32> = simd_abs(i)
    let _: Int32 = simd_reduce_max(i)
    let _: Double = simd_sign(2.0 as Double)

    var m = simd_float3x2()
    m.columns.0 = SIMD2<Float>(1, 2)
    let t: simd_float2x3 = simd_transpose(m)
    let _: Bool = simd_equal(m, simd_transpose(t))
    let _: SIMD2<Float> = simd_mul(m, v)
    let _: SIMD3<Float> = simd_mul(SIMD2<Float>(1, 2), m)
    let _: simd_float3x3 = simd_mul(t, m)
    let _: simd_float3x2 = simd_add(m, m)
    let _: simd_float3x2 = simd_sub(m, m)
    let _: simd_float3x2 = simd_mul(Float(2), m)
    var sq = simd_float4x4()
    sq.columns.3 = SIMD4<Float>(0, 0, 0, 1)
    let _: simd_float4x4 = simd_inverse(sq)
    let _: Float = simd_determinant(sq)
    let _: simd_double2x2 = simd_inverse(simd_double2x2())
    let _: simd_float4x4 = matrix_identity_float4x4
    let _: matrix_float3x3 = matrix_identity_float3x3

    let q = simd_quaternion(Float(1), SIMD3<Float>(0, 0, 1))
    let _: simd_quatf = simd_quaternion(simd_float3x3())
    let _: simd_quatf = simd_quaternion(simd_float4x4())
    let _: simd_quatf = simd_quaternion(v, w)
    let _: Float = simd_angle(q)
    let _: SIMD3<Float> = simd_axis(q)
    let _: simd_quatf = simd_conjugate(q)
    let _: simd_quatf = simd_inverse(q)
    let _: simd_quatf = simd_normalize(q)
    let _: Float = simd_length(q)
    let _: SIMD3<Float> = simd_act(q, v)
    let _: simd_float3x3 = simd_matrix3x3(q)
    let _: simd_float4x4 = simd_matrix4x4(q)
    let _: simd_quatf = simd_add(q, q)
    let _: simd_quatf = simd_sub(q, q)
    let _: simd_quatf = simd_mul(q, q)
    let _: simd_quatf = simd_mul(Float(2), q)
    let _: simd_quatf = simd_mul(q, Float(2))
    let _: Float = simd_dot(q, q)
    let _: simd_quatf = __tg_log(q)
    let _: simd_quatf = __tg_exp(q)
    let _: SIMD4<Float> = simd_make_float4(v, 1)
    let _: SIMD3<Float> = simd_make_float3(SIMD4<Float>(1, 2, 3, 4))
    let _: SIMD4<Double> = simd_make_double4(SIMD3<Double>(1, 2, 3), 1)
}
